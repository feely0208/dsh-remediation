/** 模板变量替换 */
export function renderTemplate(name, vars = {}) {
  const tpl = TEMPLATES[name];
  if (!tpl) return null;
  return tpl.replace(/\{\{(\w+)\}\}/g, (_, key) => (vars[key] !== undefined ? String(vars[key]) : `（待填写：${key}）`));
}

export function templateNames() {
  return Object.keys(TEMPLATES);
}
